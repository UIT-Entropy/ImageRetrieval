import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { imageApi } from '../api/imageSearch'
import { ImageSearchPage } from './ImageSearchPage'

const hits = ['a','b'].map((imageID, frame) => ({ imageID, frame, day: 'day1', source: 'Kitchen', hour: 8, batch: 'Batch1', videoID: 'day1_Kitchen_08', score: null, thumbnailUrl: '/a.jpg', imageUrl: '/a.jpg', objectCounts: {}, metadataObjectCounts: {} }))

function mount() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } })
  return render(<QueryClientProvider client={client}><ImageSearchPage /></QueryClientProvider>)
}

beforeEach(() => {
  sessionStorage.clear(); localStorage.clear()
  Object.defineProperty(HTMLElement.prototype, 'scrollIntoView', { configurable: true, value: vi.fn() })
  vi.spyOn(imageApi, 'dresSession').mockResolvedValue({ connected: false })
  vi.spyOn(imageApi, 'health').mockResolvedValue({ status: 'ok', images: 5000, objects: 111085, queryEncoder: 'remote', model: 'Qwen' })
  vi.spyOn(imageApi, 'facets').mockResolvedValue({ days: ['day1'], sources: ['Kitchen'], labels: ['person'], colors: ['red'], hours: [8,9] })
  vi.spyOn(imageApi, 'search').mockResolvedValue({ items: [], total: 0, ranked: false, offset: 0, limit: 60 })
})
afterEach(() => vi.restoreAllMocks())

describe('image workbench entry and shortcuts', () => {
  it('changes vector feedback without opening the inspector and submits directly', async () => {
    vi.mocked(imageApi.dresSession).mockResolvedValue({ connected: true, username: 'tester', evaluation_id: 'run1' })
    vi.mocked(imageApi.search).mockResolvedValue({ items: hits, total: 2, ranked: false, offset: 0, limit: 60 })
    vi.spyOn(imageApi, 'dresSubmit').mockResolvedValue({ http_status: 202, status: true, description: 'Pending' })
    mount()
    fireEvent.click(await screen.findByRole('button', { name: 'Like a' }))
    await waitFor(() => expect(imageApi.search).toHaveBeenLastCalledWith(expect.objectContaining({ positive_ids: ['a'], negative_ids: [] })))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    fireEvent.click(await screen.findByRole('button', { name: 'Dislike a' }))
    await waitFor(() => expect(imageApi.search).toHaveBeenLastCalledWith(expect.objectContaining({ positive_ids: [], negative_ids: ['a'] })))
    fireEvent.click(await screen.findByRole('button', { name: 'Submit a' }))
    await waitFor(() => expect(imageApi.dresSubmit).toHaveBeenCalledWith({ image_id: 'a', media_item_name: 'a', collection: '', task_id: '' }, expect.anything()))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Bỏ feedback' }))
    await waitFor(() => expect(imageApi.search).toHaveBeenLastCalledWith(expect.objectContaining({ positive_ids: [], negative_ids: [] })))
  })

  it('navigates neighbors with arrows and opens a dedicated video grid', async () => {
    sessionStorage.setItem('image-practice', 'true')
    vi.mocked(imageApi.search).mockResolvedValue({ items: hits, total: 2, ranked: false, offset: 0, limit: 60 })
    vi.spyOn(imageApi, 'detail').mockImplementation(async id => ({ ...hits[id === 'a' ? 0 : 1], objects: [], neighbors: hits, originalDescription: '', videoFrameCount: 2, videoFramePosition: id === 'a' ? 0 : 1, previousImageID: id === 'a' ? null : 'a', nextImageID: id === 'a' ? 'b' : null }))
    vi.spyOn(imageApi, 'video').mockResolvedValue({ videoID: 'day1_Kitchen_08', items: hits })
    mount()
    fireEvent.click(await screen.findByRole('img', { name: 'a' }))
    expect(await screen.findByRole('button', { name: 'Frame trước' })).toBeDisabled()
    fireEvent.keyDown(screen.getByRole('button', { name: 'Đóng inspector' }), { key: 'ArrowRight' })
    expect(await screen.findByRole('heading', { name: 'b' })).toBeVisible()
    await waitFor(() => expect(screen.getByRole('button', { name: 'Frame sau' })).toBeDisabled())
    fireEvent.click(screen.getByRole('button', { name: 'Tất cả frame' }))
    expect(await screen.findByRole('button', { name: 'Xem frame 0' })).toBeVisible()
    expect(screen.queryByRole('button', { name: 'Tìm tương tự' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Xem frame 0' }))
    expect(await screen.findByRole('heading', { name: 'a' })).toBeVisible()
    expect(await screen.findByRole('button', { name: 'Tìm tương tự' })).toBeVisible()
    fireEvent.keyDown(screen.getByRole('button', { name: 'Đóng inspector' }), { key: 'ArrowLeft' })
    expect(screen.getByRole('heading', { name: 'a' })).toBeVisible()
  })
  it('shows DRES entry first and allows practice without credentials', async () => {
    mount()
    expect(await screen.findByRole('heading', { name: 'Đăng nhập DRES' })).toBeVisible()
    expect(imageApi.search).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Luyện tập' }))
    expect(await screen.findByRole('heading', { name: 'Khám phá ảnh' })).toBeVisible()
    expect(screen.queryByLabelText('Yêu cầu agent')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Mô tả nội dung')).not.toBeInTheDocument()
  })

  it('toggles independent search and chat panels even from a focused input', async () => {
    sessionStorage.setItem('image-practice', 'true')
    mount()
    await screen.findByRole('heading', { name: 'Khám phá ảnh' })
    const event = new KeyboardEvent('keydown', { key: 's', ctrlKey: true, bubbles: true, cancelable: true })
    fireEvent(window, event)
    expect(event.defaultPrevented).toBe(true)
    const input=screen.getByRole('textbox', { name: 'Mô tả nội dung' })
    fireEvent.change(input, { target: { value: 'Keep my scene' } })
    expect(screen.queryByLabelText('Yêu cầu agent')).not.toBeInTheDocument()
    fireEvent.keyDown(input, { key: 's', ctrlKey: true })
    expect(screen.queryByLabelText('Mô tả nội dung')).not.toBeInTheDocument()
    fireEvent.keyDown(window, { key: 'a', ctrlKey: true })
    const chat=screen.getByRole('textbox', { name: 'Yêu cầu agent' })
    fireEvent.change(chat, { target: { value: 'đúng 2 người' } })
    fireEvent.keyDown(chat, { key: 'a', ctrlKey: true })
    expect(screen.queryByLabelText('Yêu cầu agent')).not.toBeInTheDocument()
    fireEvent.keyDown(window, { key: 'a', ctrlKey: true })
    expect(screen.getByLabelText('Yêu cầu agent')).toHaveValue('đúng 2 người')
    fireEvent.keyDown(window, { key: 's', ctrlKey: true })
    expect(screen.getByLabelText('Mô tả nội dung')).toHaveValue('Keep my scene')
  })

  it('logs in, selects a returned evaluation, and keeps credentials out of browser storage', async () => {
    const runs=[{ id: 'run1', name: 'Thi thử', status: 'ACTIVE' }]
    vi.spyOn(imageApi, 'dresLogin').mockResolvedValue({ connected: true, username: 'tester', server: 'https://dres.test', evaluation_id: '', evaluations: runs })
    vi.spyOn(imageApi, 'dresRuns').mockResolvedValue(runs)
    vi.spyOn(imageApi, 'dresSelect').mockResolvedValue({ connected: true, username: 'tester', server: 'https://dres.test', evaluation_id: 'run1' })
    mount()
    fireEvent.change(await screen.findByLabelText('Server URL'), { target: { value: 'https://dres.test' } })
    fireEvent.change(screen.getByLabelText('Username'), { target: { value: 'tester' } })
    fireEvent.change(screen.getByLabelText('Password'), { target: { value: 'private-password' } })
    fireEvent.click(screen.getByRole('button', { name: 'Đăng nhập DRES' }))
    const select=await screen.findByRole('combobox', { name: 'Lượt thi DRES' })
    fireEvent.change(select, { target: { value: 'run1' } })
    fireEvent.click(screen.getByRole('button', { name: 'Vào lượt thi' }))
    expect(await screen.findByRole('heading', { name: 'Khám phá ảnh' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'DRES · tester' })).toBeVisible()
    expect(localStorage.getItem('image-dres-server')).toBe('https://dres.test')
    expect(JSON.stringify({ ...localStorage, ...sessionStorage })).not.toContain('private-password')
    expect(imageApi.dresSelect).toHaveBeenCalledWith('run1', expect.anything())
  })

  it('keeps user and assistant turns when chat is collapsed and reopened', async () => {
    sessionStorage.setItem('image-practice', 'true')
    vi.spyOn(imageApi, 'parse').mockResolvedValue({ model: 'gpt-6-luna', engine: 'local', message: 'Đã chỉnh số người.', warnings: [], needs_clarification: false, query: { text: '', objects: [{ label: 'person', min_count: 2, max_count: 2 }], offset: 0, limit: 60 }, elapsedMs: 0, usage: { input_tokens: 0, output_tokens: 0 } })
    mount()
    await screen.findByRole('heading', { name: 'Khám phá ảnh' })
    fireEvent.keyDown(window, { key: 'a', ctrlKey: true })
    const input=screen.getByLabelText('Yêu cầu agent')
    fireEvent.change(input, { target: { value: 'đúng 2 người' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(await screen.findByText(/Đã chỉnh số người/)).toBeVisible()
    expect(screen.getByRole('log')).toHaveTextContent('đúng 2 người')
    fireEvent.keyDown(input, { key: 'a', ctrlKey: true })
    fireEvent.keyDown(window, { key: 'a', ctrlKey: true })
    expect(screen.getByRole('log')).toHaveTextContent('Đã chỉnh số người')
    await waitFor(() => expect(imageApi.search).toHaveBeenLastCalledWith(expect.objectContaining({ objects: [{ label: 'person', min_count: 2, max_count: 2 }] })))
  })
})
